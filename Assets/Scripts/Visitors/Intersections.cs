using UnityEngine;



/// <summary>
/// Descripción de qué es y para qué sirve
/// </summary>
public class Intersections : MonoBehaviour
{
    // ---- ATRIBUTOS DEL INSPECTOR ----
    #region Atributos del Inspector (serialized fields)
    // Documentar cada atributo que aparece aquí.
    // Los atributos públicos y de inspector en formato PascalCase
    [SerializeField] private bool intersection;
    #endregion

    // ---- ATRIBUTOS PRIVADOS ----
    #region Atributos Privados (private fields)
    // Documentar cada atributo que aparece aquí.
    // Los atributos privados en formato _camelCase
    /// <summary>
    /// Componente del visitante que entra en la interseccion
    /// </summary>
    private VisitorsMovement _vistor;
    /// <summary>
    /// Componente del trabajador que entra en la interseccion
    /// </summary>
    private WorkerMovement _worker;
    #endregion
    
    // ---- MÉTODOS DE MONOBEHAVIOUR ----
    #region Métodos de MonoBehaviour
    
    /// <summary>
    /// Start is called on the frame when a script is enabled just before 
    /// any of the Update methods are called the first time.
    /// </summary>
    void Start()
    {
        
    }

    /// <summary>
    /// Update is called every frame, if the MonoBehaviour is enabled.
    /// </summary>
    void Update()
    {
        
    }

    #endregion

    // ---- MÉTODOS PÚBLICOS ----
    #region Métodos públicos
    // Documentar cada método que aparece aquí con ///<summary>
    // Estos métodos se nombren en formato PascalCase
    #endregion

    // ---- MÉTODOS PRIVADOS ----
    #region Métodos Privados
    // Documentar cada método que aparece aquí con ///<summary>
    // Estos métodos se nombren en formato PascalCase
    private void OnTriggerEnter2D(Collider2D collision)
    {
        _vistor = collision.GetComponent<VisitorsMovement>();
        if (_vistor)
        {
            _vistor.changeDir(intersection);
        }
        else
        {
            _worker = collision.GetComponent<WorkerMovement>();
            if (_worker)
            {
                // 1 de cada 3 veces cambiamos la direccion
                if (UnityEngine.Random.Range(0, 3) == 1) _worker.ChangeDir(intersection);
            }
        }
    }
    #endregion   

} // class Intersections 
// namespace
