using TMPro;
using UnityEngine;



/// <summary>
/// Se asocia con una zona que puedes comprar
/// </summary>
public class CompraZona : MonoBehaviour
{
    // ---- ATRIBUTOS DEL INSPECTOR ----
    #region Atributos del Inspector (serialized fields)
    // Documentar cada atributo que aparece aquí.
    // Los atributos públicos y de inspector en formato PascalCase

    [SerializeField] private GameObject ZonaComprada = null;
    [SerializeField] private TextMeshProUGUI InfoCompra;
    [SerializeField] private float Precio;
    #endregion
    
    // ---- ATRIBUTOS PRIVADOS ----
    #region Atributos Privados (private fields)
    // Documentar cada atributo que aparece aquí.
    // Los atributos privados en formato _camelCase

    #endregion
    
    // ---- MÉTODOS DE MONOBEHAVIOUR ----
    #region Métodos de MonoBehaviour
    
    /// <summary>
    /// Start is called on the frame when a script is enabled just before 
    /// any of the Update methods are called the first time.
    /// </summary>
    void Start()
    {
        if (ZonaComprada != null) ZonaComprada.SetActive(false);
        InfoCompra.text = "Precio: " + Precio + "€";
    }

    /// <summary>
    /// Update is called every frame, if the MonoBehaviour is enabled.
    /// </summary>
    void Update()
    {
        
    }

    #endregion

    // ---- MÉTODOS PÚBLICOS ----
    #region Métodos públicos
    // Documentar cada método que aparece aquí con ///<summary>
    // Estos métodos se nombren en formato PascalCase
    public void ComprarZona()
    {
        if (GameManager.Instance.GastaDinero(Precio))
        {
            Debug.Log("Compra realizada");
            this.gameObject.SetActive(false);
            if (ZonaComprada != null) ZonaComprada.SetActive(true);
        }
    }
    #endregion
    
    // ---- MÉTODOS PRIVADOS ----
    #region Métodos Privados
    // Documentar cada método que aparece aquí con ///<summary>
    // Estos métodos se nombren en formato PascalCase

    #endregion   

} // class CompraZona 
// namespace
